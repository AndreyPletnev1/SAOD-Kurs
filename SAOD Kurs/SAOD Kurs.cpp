const int N = 10, M = 10; // Размер лабиринта
char maze[N][M];
bool visited[N][M];

int dx[] = { -1, 1, 0, 0 };
int dy[] = { 0, 0, -1, 1 };
string dir[] = { "вверх", "вниз", "влево", "вправо" };

bool isValid(int x, int y) {
    return x >= 0 && y >= 0 && x < N && y < M && maze[x][y] != '#' && !visited[x][y];
}

bool solveMaze(int x, int y, vector<string>& path) {
    if (maze[x][y] == 'E') return true;

    visited[x][y] = true;

    for (int i = 0; i < 4; i++) {
        int nx = x + dx[i];
        int ny = y + dy[i];
        if (isValid(nx, ny)) {
            path.push_back(dir[i]);
            if (solveMaze(nx, ny, path)) return true;
            path.pop_back();
        }
    }

    return false;
}

void resetMaze() {
    for (int i = 0; i < N; ++i)
        for (int j = 0; j < M; ++j)
            maze[i][j] = '.', visited[i][j] = false;
}

void runComparison() {
    vector<pair<string, function<void()>>> scenarios = {
        {"Простой лабиринт", []() {
            resetMaze();
            maze[0][0] = 'S';
            maze[N - 1][M - 1] = 'E';
        }},
        {"Сложный лабиринт с преградами", []() {
            resetMaze();
            maze[0][0] = 'S';
            maze[N - 1][M - 1] = 'E';
            for (int i = 1; i < 9; i++) maze[i][5] = '#';
        }},
        {"Лабиринт без выхода", []() {
            resetMaze();
            maze[0][0] = 'S';
            maze[1][0] = '#';
            maze[0][1] = '#';
        }},
        {"Случайный лабиринт", []() {
            resetMaze();
            maze[0][0] = 'S';
            maze[N - 1][M - 1] = 'E';
            random_device rd; mt19937 gen(rd());
            uniform_int_distribution<> d(0, N - 1);
            for (int i = 0; i < 20; i++) maze[d(gen)][d(gen)] = '#';
        }}
    };

    for (const auto& scenario : scenarios) {
        const string& desc = scenario.first;
        const auto& setup = scenario.second;
        setup();
        vector<string> path;
        auto start = high_resolution_clock::now();

        int sx = -1, sy = -1;
        for (int i = 0; i < N; ++i)
            for (int j = 0; j < M; ++j)
                if (maze[i][j] == 'S') sx = i, sy = j;

        bool found = solveMaze(sx, sy, path);
        auto end = high_resolution_clock::now();
        auto duration = duration_cast<nanoseconds>(end - start);

        cout << "\nСценарий: " << desc << endl;
        cout << "Результат: " << (found ? "Путь найден" : "Путь не найден")
            << ", время: " << duration.count() / 1e6 << " мс\n";
    }
}

